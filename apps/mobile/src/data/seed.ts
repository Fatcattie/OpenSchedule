const DAY_MS = 86_400_000
/** 演示时区固定为 UTC+8（与 mock 用户 timezone 一致） */
const DEMO_TZ_OFFSET_MS = 8 * 60 * 60 * 1000

/**
 * 演示当日（Asia/Shanghai）某时刻的 ISO8601 UTC 字符串。
 * 时间随运行日滚动，保证「今日聚焦 / 时间容器」始终有当天数据。
 */
export function demoDayAt(offsetDays: number, hour: number, minute = 0): string {
  const now = new Date()
  const local = new Date(now.getTime() + DEMO_TZ_OFFSET_MS)
  const utcMs =
    Date.UTC(local.getUTCFullYear(), local.getUTCMonth(), local.getUTCDate(), hour, minute, 0, 0) -
    DEMO_TZ_OFFSET_MS +
    offsetDays * DAY_MS
  return new Date(utcMs).toISOString()
}

/** 相对今天偏移 N 天的 ISO 时间（默认 18:00，随演示日滚动） */
export function day(offsetDays: number): string {
  return demoDayAt(offsetDays, 18, 0)
}

